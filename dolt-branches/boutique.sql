-- Three views: saved queries that always use the data on the current branch.
-- Revenue and profit assume each sale was at the current price of the product.

-- 1. Units, revenue and profit for each category.
CREATE VIEW category_summary AS
SELECT p.category,
       SUM(s.quantity) AS units_sold,
       SUM(s.quantity * p.price) AS revenue,
       SUM(s.quantity * (p.price - p.cost)) AS profit
FROM sales s
JOIN products p ON p.product_id = s.product_id
GROUP BY p.category
ORDER BY revenue DESC;

-- 2. Revenue and profit for each store.
CREATE VIEW store_summary AS
SELECT s.store,
       COUNT(*) AS number_of_sales,
       SUM(s.quantity * p.price) AS revenue,
       SUM(s.quantity * (p.price - p.cost)) AS profit
FROM sales s
JOIN products p ON p.product_id = s.product_id
GROUP BY s.store
ORDER BY revenue DESC;

-- 3. Price, margin and revenue for each product.
CREATE VIEW product_margins AS
SELECT p.product_id,
       p.product_name,
       p.color,
       p.cost,
       p.price,
       ROUND((p.price - p.cost) / p.price * 100, 1) AS margin_percent,
       COALESCE(SUM(s.quantity), 0) AS units_sold,
       COALESCE(SUM(s.quantity * p.price), 0) AS revenue
FROM products p
LEFT JOIN sales s ON s.product_id = p.product_id
GROUP BY p.product_id, p.product_name, p.color, p.cost, p.price
ORDER BY revenue DESC;
